def pandoc_bin():
    try:
        import pypandoc
        return pypandoc.get_pandoc_path()
    except Exception:
        return "pandoc"


def pandoc(md):
    r = subprocess.run([pandoc_bin(), "-f", "markdown-implicit_figures-fancy_lists", "-t", "latex", "--natbib", "--wrap=none"],
                       input=md.encode("utf-8"), capture_output=True)
    if r.returncode != 0:
        raise SystemExit(r.stderr.decode("utf-8", "replace"))
    return r.stdout.decode("utf-8").replace("\r\n", "\n")   # pandoc on Windows writes CRLF


UNI = {"−": r"\textminus{}", "°": r"\textdegree{}", "±": r"$\pm$", "²": r"$^2$", "×": r"$\times$", "≤": r"$\le$",
       "≥": r"$\ge$", "√": r"$\surd$", "…": r"\ldots{}", "→": r"$\rightarrow$", "≈": r"$\approx$", "–": "--"}


def unicode_fix(t):
    for k, v in UNI.items():
        t = t.replace(k, v)
    return t


# ---------------------------------------------------------------- tables from the generated sources
def esc(c):
    """A generated cell -> LaTeX text: escapes, minus signs, '-' for 'not applicable'."""
    if c.strip() in ("-", "NaN"):
        return "--"
    c = c.replace("%", r"\%").replace("_", r"\_").replace("&", r"\&").replace("NaN", "--")
    c = re.sub(r"(?<![\w.])-(?=\d)", lambda m: "$-$", c)
    c = re.sub(r"(?<= )-(?= )", lambda m: "$-$", c)
    return unicode_fix(c)


def lookup(d, c, what):
    if c not in d:
        raise SystemExit(f"build_tex: no paper wording for {what} {c!r} - add it to the map")
    return d[c]


