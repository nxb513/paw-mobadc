function L = table2(root)
L = {'', '## Table 2 - Guo''s controllers on circle_main (dev)', ''};
[Z, cols, ok] = p2r_load(root, 'gd6/guo_p2.mat');
if ~ok, L{end + 1} = '`gd6/guo_p2.mat` not found.'; return; end
[E, day, ~, keep] = p2r_subset(Z, cols, cols, 'one4');
E = E(keep, :);  day = day(keep);
P = sqrt(mean(E.^2, 1));
L{end + 1} = sprintf('One set %d of %d segments, %d days. Role: DESCRIPTIVE (reproduction of Guo et al. 2020).', ...
    size(E, 1), numel(keep), numel(unique(day)));
L{end + 1} = '';
L{end + 1} = '| controller | pooled [m] | vs PID (SE; LOO; by-day) |';
L{end + 1} = '|---|---|---|';
for c = 1:numel(cols)
    if c == 1, s = '-'; else, s = fmt(p2r_stat(@(p) p(2) / p(1) - 1, E(:, [1 c]), day)); end
    L{end + 1} = sprintf('| %s | %.5f | %s |', p2_names(cols{c}), P(c), s); %#ok<AGROW>
end
[Zt, ct, okt] = p2r_load(root, 'gd6/guo_trim_p2.mat');
if ~okt, L{end + 1} = ''; L{end + 1} = '`gd6/guo_trim_p2.mat` not found.'; return; end
for c = 1:numel(ct)
    base = strrep(ct{c}, '+trim', '');
    [Ej, dj] = joinrows(Z, cols, {base, 'MOBADC'}, Zt, ct, ct(c));
    s1 = fmt(p2r_stat(@(p) p(3) / p(1) - 1, Ej, dj));
    s2 = fmt(p2r_stat(@(p) p(3) / p(2) - 1, Ej, dj));
    L{end + 1} = sprintf('| %s | %.5f | vs %s: %s; vs MOBADC: %s (n %d) |', p2_names(ct{c}), sqrt(mean(Ej(:, 3).^2)), p2_names(base), ...
        s1, s2, size(Ej, 1)); %#ok<AGROW>
end
end

