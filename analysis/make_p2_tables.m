function make_p2_tables(varargin)
%MAKE_P2_TABLES  GD11 tables 1-6 (REGISTER_P2 sec 62.2, 63.2-63.3) -> paper/tables/tables_p2.md, from saved results only.
%
%   make_p2_tables
%   make_p2_tables('Out', 'tables.md', 'Root', 'results')
%
%  1 parameters (read from core/p2_params.m and init_MOBADC_params at run time, labelled [PAPER] / [THIS WORK] /
%    [DERIVED]); 2 Guo's controllers on circle_main (+ trim); 3 the claims, dev and CONFIRM2, with u_osc and theta RMS
%    of the compared columns; 4 sensitivity on S40 circle at every m_p / L level and 2^2 corner (m_p 0.25 rows on
%    U <= 7.38 m/s, sec 50.1) + a trend sentence generated from the numbers; 5 main comparison on dev circle_main
%    (sec 63.2: PID / DO (+ trim), ESO, MOBADC, INDI-DE, PAW-MOBADC; mean, Guo STD, theta RMS); 6 ablation
%    MOBADC-W -> PA-MOBADC -> PAW-MOBADC (sec 63.3). Names: analysis/p2_names.m. Statistics: analysis/p2r_stat.m.
opt = struct('Out', fullfile(repo_root(), 'paper', 'tables', 'tables_p2.md'), 'Root', fullfile(repo_root(), 'results'));
for i = 1:2:numel(varargin)
    assert(isfield(opt, varargin{i}), 'make_p2_tables: unknown option ''%s''.', varargin{i});
    opt.(varargin{i}) = varargin{i+1};
end
[st, gh] = system('git rev-parse --short HEAD');  if st ~= 0, gh = 'unknown'; end
L = {};
L{end + 1} = '# TABLES_P2 - tables 1-6 of the paper (generated)';
L{end + 1} = '';
L{end + 1} = sprintf(['> Generated by `analysis/make_p2_tables.m` at git `%s` on %s (REGISTER_P2 sec 62.2). Do not ' ...
    'edit by hand. Statistics: pooled = sqrt(mean(m_i^2)); SE = paired day jackknife; LOO [min, max]; by-day median.'], ...
    strtrim(gh), datestr(now, 'yyyy-mm-dd HH:MM'));
L = [L, table1(), table2(opt.Root), table3(opt.Root), table4(opt.Root), table5(opt.Root), table6(opt.Root)];
fid = fopen(opt.Out, 'w');
assert(fid > 0, 'make_p2_tables: cannot write %s.', opt.Out);
fprintf(fid, '%s\n', L{:});
fclose(fid);
fprintf('  wrote %s\n', opt.Out);
end

