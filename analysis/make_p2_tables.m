function [E, day] = joinrows(Za, ca, wa, Zb, cb, wb)
%JOINROWS  Columns wa of file a and wb of file b on the segments present and finite in both (by file name).
Ea = p2r_E(Za, ca, wa);  Eb = p2r_E(Zb, cb, wb);
fa = {Za.rows.file};  fb = {Zb.rows.file};
[~, ia, ib] = intersect(fa, fb);
E = [Ea(ia, :), Eb(ib, :)];
day = {Za.rows(ia).day}';
Ka = p2r_E(Za, ca, ca);                                 % one set of file a (all its columns) on the shared segments
k = all(isfinite(E), 2) & all(isfinite(Ka(ia, :)), 2);
E = E(k, :);  day = day(k);
end

