function v = verdict(test, r, Z, cols, ab)
suff = r.n >= 15 && r.nd >= 6;
switch test
    case 'd2dev', v = tern(r.val <= -0.30 && r.loo(2) < 0, 'PASS (sec 0.5)', 'FAIL (sec 0.5)');
    case 'd2'
        if ~suff, v = 'NOT CONFIRMABLE'; else, v = tern(r.val <= -0.15 && r.val + 1.65 * r.se < 0, 'CONFIRMED', 'NOT CONFIRMED'); end
    case 'hs'
        E = p2r_E(Z, cols, ab);
        nu = sum(isfinite(E(:, 1)) & ~isfinite(E(:, 2)));
        if ~suff, v = 'NOT CONFIRMABLE';
        else, v = tern(r.med >= 0.10 && r.val - 1.65 * r.se > 0 && nu <= 1, 'CONFIRMED', 'NOT CONFIRMED'); end
        v = sprintf('%s (n_unsafe %d)', v, nu);
    case 'hh'
        if ~suff, v = 'NOT CONFIRMABLE'; else, v = tern(r.med >= 0.10 && r.val - 1.65 * r.se > 0, 'CONFIRMED', 'NOT CONFIRMED'); end
    otherwise, v = '-';
end
end

function [u, th] = effort(Z, cols, ab, keep)
%EFFORT  pooled u_osc (rows.Q(5,:), CONFIRM2 only) and pooled theta RMS (p2 theta_rms_stat_deg) of columns a, b.
u = '-';
if isfield(Z.rows, 'Q')
    q = nan(numel(Z.rows), 2);
    for c = 1:2
        j = find(strcmp(cols, ab{c}), 1);
        for i = 1:numel(Z.rows), q(i, c) = Z.rows(i).Q(5, j); end
    end
    q = q(keep, :);
    u = sprintf('%.3f / %.3f', sqrt(mean(q.^2, 1)));
end
t = p2r_p2(Z, cols, ab, 'theta_rms_stat_deg');
t = t(keep, :);
th = '-';
if all(isfinite(t(:))), th = sprintf('%.2f / %.2f', sqrt(mean(t.^2, 1))); end
end

