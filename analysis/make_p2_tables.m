function L = limits_note(C, codes, fl)
%LIMITS_NOTE  Segments of the one set at the tilt clamp (tilt_sat_frac >= 1 %) in a row - they dominate the pooled STD
%  (one bad segment's within-segment STD enters squared) - and the theta note: no theta standard deviation is
%  stored, so theta RMS is reported with the steady cone angle of the circle (conical pendulum, no wind).
L = {};
hit = {};  per = cell(1, numel(C));
for k = 1:numel(C)
    [~, loc] = ismember(fl, C(k).file);
    t = C(k).TS(loc);
    per{k} = sprintf('%s %d', p2_names(codes{k}), sum(t >= 0.01));
    hit = union(hit, fl(t >= 0.01));
end
g = 9.81;  R = 0.8;  w = 1.575;  Lc = 1.0;  th = 0.2;      % circle Test 4 (MOBADC_FIDELITY E17 / op_set), L 1.0 m
for it = 1:200, th = atan(w^2 * (R + Lc * sin(th)) / g); end
L{end + 1} = sprintf(['- The pooled STD (sqrt(mean s_i^2)) is dominated by the segments at the actuator limit: %d ' ...
    'segment(s) of the set have the tilt clamp active >= 1 %% of the time in at least one row (per row: %s): %s. The ' ...
    'medians over segments are given beside the pooled values.'], numel(hit), strjoin(per, ', '), ...
    strjoin(cellfun(@(f) ['`' f '`'], hit(:)', 'UniformOutput', false), ', '));
L{end + 1} = sprintf(['- theta RMS is mostly the steady cone angle of the payload on the circle, not swing: a conical ' ...
    'pendulum on this circle without wind has tan(theta_c) = omega^2 (R + L sin(theta_c)) / g, theta_c = %.1f deg ' ...
    '(R %.1f m, omega %.3f rad/s, L %.1f m). The result files store no standard deviation of theta, so the oscillation ' ...
    'about that angle is not reported.'], rad2deg(th), R, w, Lc);
end

