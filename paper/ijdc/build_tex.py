# ---------------------------------------------------------------- manuscript conversion
def split_sections(md):
    """[(level, title, body)] for '## ' / '### ' headings."""
    parts = re.split(r"^(#{2,3}) (.+)$", md, flags=re.M)
    out = [(0, "", parts[0])]
    for i in range(1, len(parts), 3):
        out.append((len(parts[i]), parts[i + 1].strip(), parts[i + 2]))
    return out


def sec_name(ttl):
    return re.sub(r"^(\d+(\.\d+)?\.?|Appendix [A-Z]\.)\s*", "", ttl)


def sec_label(name):
    return "sec:" + re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def inline_table(md_block):
    rows = [ln for ln in md_block.strip().splitlines() if ln.startswith("|")]
    rows = [r for r in rows if not re.match(r"^\|[-|\s]+\|$", r)]
    cells = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows]
    n = len(cells[0])

    def conv(c):
        x = pandoc(equations(c)).strip()
        return x if x else c

    spec = "p{0.32\\linewidth}p{0.6\\linewidth}" if n == 2 else "p{0.46\\linewidth}" + "p{0.22\\linewidth}" * (n - 1)
    lines = [" & ".join(r"\textbf{" + conv(c) + "}" for c in cells[0]) + r" \\", r"\midrule"]
    lines += [" & ".join(conv(c) for c in r) + r" \\" for r in cells[1:]]
    return ("\n\\begin{center}\\footnotesize\n\\begin{tabular}{@{}" + spec + "@{}}\n\\toprule\n" + "\n".join(lines) +
            "\n\\botrule\n\\end{tabular}\n\\end{center}\n")


def protect_tables(body, store):
    def rep(m):
        store.append(inline_table(m.group(0)))
        return f"\n\nTABLEPLACEHOLDER{len(store) - 1}\n\n"
    return re.sub(r"(?:^\|.*\|\s*$\n?)+", rep, body, flags=re.M)


SPLIT = {"eq:ff-err"}   # wider than the text block of the template (overfull in the LaTeX log): two lines


def eq_body(body, label):
    body = body.strip()
    if label in SPLIT:
        body = "\\begin{gathered}\n" + body.replace(",\\qquad", ",\\\\") + "\n\\end{gathered}"
    return body


def equations(md):
    md = re.sub(r"\$\$(.+?)\$\$\s*\{#(eq:[A-Za-z0-9_-]+)\}",
                lambda m: "\n\\begin{equation}\n" + eq_body(m.group(1), m.group(2)) + "\n\\label{" + m.group(2)
                + "}\n\\end{equation}\n", md, flags=re.S)
    md = re.sub(r"\(@(eq:[A-Za-z0-9_-]+)\)", lambda m: "\\eqref{" + m.group(1) + "}", md)
    md = re.sub(r"@(eq:[A-Za-z0-9_-]+)", lambda m: "Eq.~\\eqref{" + m.group(1) + "}", md)
    return md


def propositions(tex):
    tex = re.sub(r"\\textbf\{(Proposition \d+) \((.+?)\)\.\}\s*", lambda m: "\\begin{proposition}[" + m.group(2) + "]\n",
                 tex)
    # a proposition ends where its proof starts; a proof ends at \square
    tex = re.sub(r"\n\s*\\emph\{Proof\.\}\s*", lambda m: "\n\\end{proposition}\n\\begin{proof}\n", tex)
    tex = re.sub(r"\s*\\\(\\square\\\)", lambda m: "\n\\end{proof}", tex)
    tex = re.sub(r"\s*\$\\square\$", lambda m: "\n\\end{proof}", tex)
    return tex


def cross_refs(tex, secmap):
    num = r"\d+(?:\.\d+)?(?!\.\d)"

    def sec(n):
        if n not in secmap:
            raise SystemExit(f"build_tex: Section {n} cited but no such heading")
        return "\\ref{" + secmap[n] + "}"

    def secs(m):
        word, rest = m.group(1), m.group(2)
        rest = re.sub(r"(\d+(?:\.\d+)?)--(\d+(?:\.\d+)?)", lambda k: sec(k.group(1)) + "--" + sec(k.group(2)), rest)
        rest = re.sub(r"(?<![{\w.-])(\d+(?:\.\d+)?)(?![\w.}-]*\})", lambda k: sec(k.group(1)), rest)
        return word + "~" + rest

    tex = re.sub(r"\b(Sections?) (" + num + r"(?:(?:, | and |--)" + num + r")*)", secs, tex)
    tex = re.sub(r"\bFig\. (\d+)", lambda m: "Fig.~\\ref{fig:" + m.group(1) + "}", tex)
    tex = re.sub(r"\bTable (\d+)", lambda m: "Table~\\ref{" + TABLABEL[int(m.group(1))] + "}", tex)
    tex = re.sub(r"et al\.~(?=[A-Z])", lambda m: "et al.\\@ ", tex)
    return tex


def figures(md):
    caps = {}
    for m in re.finditer(r"\*\*Fig\. (\d+)\*\* \(`([^`]+)`\)\. (.+?)(?=\n\n|\Z)", md, re.S):
        caps[int(m.group(1))] = (m.group(2), " ".join(m.group(3).split()))
    return caps


def fig_env(n, f, cap):
    capt = pandoc(cap).strip()
    return (f"\n\\begin{{figure}}[!htbp]\n\\centering\n\\includegraphics[width=\\linewidth]{{{f}.pdf}}\n"
            f"\\caption{{{capt}}}\\label{{fig:{n}}}\n\\end{{figure}}\n")


