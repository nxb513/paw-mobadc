def t1_source(s):
    if s.startswith("[PAPER] Guo 2020"):
        return "Guo et al. \\cite{guo2020}"
    if s == "[DERIVED]":
        return "derived (Section~\\ref{sec:wind-and-the-two-disturbance-paths})"
    if "measured on dev" in s:
        return "measured, development set"
    if "assumption" in s:
        return "this work (assumed)"
    if s.startswith("[THIS WORK]"):
        return "this work"
    raise SystemExit(f"build_tex: no paper wording for the Table 1 source {s!r}")


def t1_value(v):
    for a, b in T1_VALUE:
        v = re.sub(a, b, v)
    v = esc(v)
    for a, b in T1_TEX:
        v = v.replace(a, b)
    return v


