    ['| block | n (days) | MOBADC-W | PA-MOBADC | PAW-MOBADC | C1: PA-MOBADC / MOBADC-W - 1 | C2: PAW-MOBADC / ' ...
     'PA-MOBADC - 1 | total: PAW-MOBADC / MOBADC-W - 1 |'], '|---|---|---|---|---|---|---|---|'};
B = {'circle, dev circle_main', {'L2', 'gd6/d2_p2.mat'; 'L3', 'gd6/d2_p2.mat'; 'L3_iii0', 'gd7/six-circle-h3.mat'};
     'circle, CONFIRM2', {'L2', 'gd10/D2.mat'; 'L3', 'gd10/D2.mat'; 'L3_iii0', 'gd10/C2-circle.mat'};
     'hover, dev N6_hover', {'L3', 'gd7/static-hover.mat'; 'L3_iii0', 'gd7/static-hover.mat'};
     'hover, dev N6_hover, subset A', {'L3', 'gd7/static-hover.mat'; 'L3_iii0', 'gd7/static-hover.mat'};
     'hover, CONFIRM2', {'L3', 'gd10/C2-hover.mat'; 'L3_iii0', 'gd10/C2-hover.mat'}};
rel = @(p) p(1) / p(2) - 1;
notes = {};
for b = 1:size(B, 1)
    src = B{b, 2};
    C = loadcols(root, src);
    if ~all([C.ok])
        L{end + 1} = sprintf('| %s | missing: %s | | | | | | |', B{b, 1}, strjoin(unique(src(~[C.ok], 2))', ', ')); %#ok<AGROW>
        continue
    end
    [fl, day] = oneset(C);
    if ~isempty(strfind(B{b, 1}, 'subset A'))          % sec 60.3 subset A: PA-MOBADC tilt clamp < 1 %
        [~, loc] = ismember(fl, C(1).file);
        keepA = C(1).TS(loc) < 0.01;
        fl = fl(keepA);  day = day(keepA);
    end
    ex = excluded(C, src(:, 1));
    if ~isempty(strfind(B{b, 1}, 'subset A')), ex = {}; end
    if ~isempty(ex), notes{end + 1} = sprintf('%s: %s', B{b, 1}, ex{2}(3:end)); end %#ok<AGROW>
    E = nan(numel(fl), size(src, 1));
    for k = 1:size(src, 1)
        [~, loc] = ismember(fl, C(k).file);  E(:, k) = C(k).E(loc);
    end
    P = sqrt(mean(E.^2, 1));
    w = strcmp(src(:, 1), 'L2');  a = find(strcmp(src(:, 1), 'L3'));  c = find(strcmp(src(:, 1), 'L3_iii0'));
    c2 = fmt(p2r_stat(rel, E(:, [c a]), day));
    if any(w)
        iw = find(w);
        c1 = fmt(p2r_stat(rel, E(:, [a iw]), day));  tot = fmt(p2r_stat(rel, E(:, [c iw]), day));  pw = sprintf('%.5f', P(iw));
    else
        c1 = '-';  tot = '-';  pw = '-';
    end
    L{end + 1} = sprintf('| %s | %d (%d) | %s | %.5f | %.5f | %s | %s | %s |', B{b, 1}, numel(fl), numel(unique(day)), ...
        pw, P(a), P(c), c1, c2, tot); %#ok<AGROW>
    if strcmp(B{b, 1}, 'hover, dev N6_hover')               % what drives the full-set value: the most influential segment
        loo = nan(numel(fl), 1);
        for i = 1:numel(fl), q = E([1:i-1, i+1:end], :);  P2 = sqrt(mean(q.^2, 1));  loo(i) = P2(c) / P2(a) - 1; end
        [~, iw] = max(abs(loo - (P(c) / P(a) - 1)));
        hov = sprintf(['hover, dev N6_hover: on the full set (%d) the most influential segment is `%s` (PA-MOBADC ' ...
            '%.4f m, PAW-MOBADC %.4f m); without it the C2 step moves from %+.2f %% to %+.2f %%. The next row is subset ' ...
            'A (PA-MOBADC tilt clamp < 1 %%, the CONFIRM2 scoring subset of sec 60.3). On CONFIRM2 hover the C2 step is ' ...
            '%s on subset A and %s on the full set.'], ...
            numel(fl), fl{iw}, E(iw, a), E(iw, c), 100 * (P(c) / P(a) - 1), 100 * loo(iw), c2sub(root, 'unsatL3'), ...
            c2sub(root, 'one'));
        notes{end + 1} = hov; %#ok<AGROW>
    end
end
for k = 1:numel(notes), L = [L, {'', ['- ' notes{k}]}]; end %#ok<AGROW>
end

function s = c2sub(root, sub)
%C2SUB  CONFIRM2 hover C2 step PAW-MOBADC / PA-MOBADC - 1 on a subset (for the table 6 note).
s = 'n/a';
[Z, cols, ok] = p2r_load(root, 'gd10/C2-hover.mat');
if ~ok, return; end
[E, day, ~, keep] = p2r_subset(Z, cols, {'L3_iii0', 'L3'}, sub);
if sum(keep) < 2, return; end
r = p2r_stat(@(p) p(1) / p(2) - 1, E(keep, :), day(keep));
s = sprintf('%+.2f %%', 100 * r.val);
end

function L = excluded(C, codes)
%EXCLUDED  The segments the one-set rule leaves out, and which columns are not finite there (stated, never silent).
L = {};
al = {};
for k = 1:numel(C), al = union(al, C(k).file); end
[fl, ~] = oneset(C);
out = setdiff(al, fl);
if isempty(out), return; end
s = cell(1, numel(out));
for i = 1:numel(out)
    bad = {};
    for k = 1:numel(C)
        j = find(strcmp(C(k).file, out{i}), 1);
        if isempty(j), bad{end + 1} = [p2_names(codes{k}) ' (no row)']; %#ok<AGROW>
        elseif ~isfinite(C(k).E(j)), bad{end + 1} = [p2_names(codes{k}) ' not finite']; end %#ok<AGROW>
    end
    s{i} = sprintf('`%s`: %s', out{i}, strjoin(bad, ', '));
end
L = {'', sprintf('- %d segment(s) left out by the one-set rule: %s.', numel(out), strjoin(s, '; '))};
end

function C = loadcols(root, src)
%LOADCOLS  One column per row of src {code, file}: E, SD (rows.SD), theta RMS (p2), file and day lists.
C = struct('E', {}, 'SD', {}, 'TH', {}, 'TS', {}, 'file', {}, 'day', {}, 'ok', {});
for k = 1:size(src, 1)
    [Z, cols, ok] = p2r_load(root, src{k, 2});
    if ~ok || ~any(strcmp(cols, src{k, 1})), C(k).ok = false; continue; end
    j = find(strcmp(cols, src{k, 1}), 1);
    C(k).ok = true;  C(k).file = {Z.rows.file}';  C(k).day = {Z.rows.day}';
    C(k).E = p2r_E(Z, cols, src(k, 1));
    C(k).SD = nan(numel(Z.rows), 1);
    if isfield(Z.rows, 'SD'), C(k).SD = arrayfun(@(r) r.SD(j), Z.rows(:)); end
    C(k).TH = p2r_p2(Z, cols, src(k, 1), 'theta_rms_stat_deg');
    C(k).TS = p2r_p2(Z, cols, src(k, 1), 'tilt_sat_frac');
end
end

function [fl, day] = oneset(C)
%ONESET  Segments finite in every given column (by file name), with their days.
fl = C(1).file(isfinite(C(1).E));
for k = 2:numel(C), fl = intersect(fl, C(k).file(isfinite(C(k).E))); end
[~, loc] = ismember(fl, C(1).file);
day = C(1).day(loc);
end

function s = qm(v, f)
%QM  Pooled quadratic mean, or "-" if any value is missing (not stored).
s = '-';
if ~isempty(v) && all(isfinite(v)), s = sprintf(f, sqrt(mean(v.^2))); end
end

